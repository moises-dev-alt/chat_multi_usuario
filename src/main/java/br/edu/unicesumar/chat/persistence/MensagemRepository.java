package br.edu.unicesumar.chat.persistence;

import br.edu.unicesumar.chat.model.Mensagem;
import br.edu.unicesumar.chat.model.Usuario;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.Timestamp;
import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;

/** Unico ponto de acesso SQL da aplicacao. */
public class MensagemRepository {
    private static final String CRIAR_TABELA = "CREATE TABLE IF NOT EXISTS mensagens ("
            + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "remetente VARCHAR(50) NOT NULL, conteudo VARCHAR(1000) NOT NULL, horario TIMESTAMP NOT NULL, grupo VARCHAR(60) NOT NULL DEFAULT 'Geral')";
    private final String url;

    public MensagemRepository(String url) {
        this.url = url;
        inicializar();
    }

    private Connection abrirConexao() throws SQLException {
        return DriverManager.getConnection(url);
    }

    private void inicializar() {
        try (Connection conexao = abrirConexao(); Statement comando = conexao.createStatement()) {
            comando.execute(CRIAR_TABELA);
            try {
                comando.execute("ALTER TABLE mensagens ADD COLUMN grupo VARCHAR(60) NOT NULL DEFAULT 'Geral'");
            } catch (SQLException ignored) {
                // A coluna ja existe em bancos criados com a versao atual.
            }
        } catch (SQLException e) {
            throw new IllegalStateException("Nao foi possivel inicializar o banco de dados.", e);
        }
    }

    public void salvar(Mensagem mensagem) {
        String sql = "INSERT INTO mensagens (remetente, conteudo, horario, grupo) VALUES (?, ?, ?, ?)";
        try (Connection conexao = abrirConexao(); PreparedStatement comando = conexao.prepareStatement(sql)) {
            comando.setString(1, mensagem.getRemetente().getNome());
            comando.setString(2, mensagem.getConteudo());
            comando.setTimestamp(3, Timestamp.valueOf(mensagem.getHorario()));
            comando.setString(4, mensagem.getGrupo());
            comando.executeUpdate();
        } catch (SQLException e) {
            throw new IllegalStateException("Nao foi possivel salvar a mensagem.", e);
        }
    }

    public List<Mensagem> buscarUltimas(int limite) {
        return buscarUltimas("Geral", limite);
    }

    public List<Mensagem> buscarUltimas(String grupo, int limite) {
        if (limite <= 0) return Collections.emptyList();
        String sql = "SELECT remetente, conteudo, horario, grupo FROM mensagens WHERE grupo = ? ORDER BY horario DESC, id DESC LIMIT ?";
        List<Mensagem> mensagens = new ArrayList<>();
        try (Connection conexao = abrirConexao(); PreparedStatement comando = conexao.prepareStatement(sql)) {
            comando.setString(1, grupo);
            comando.setInt(2, limite);
            try (ResultSet resultado = comando.executeQuery()) {
                while (resultado.next()) {
                    mensagens.add(new Mensagem(new Usuario(resultado.getString("remetente")),
                            resultado.getString("conteudo"),
                            resultado.getTimestamp("horario").toLocalDateTime(),
                            resultado.getString("grupo")));
                }
            }
        } catch (SQLException e) {
            throw new IllegalStateException("Nao foi possivel recuperar o historico.", e);
        }
        Collections.reverse(mensagens);
        return mensagens;
    }
}
